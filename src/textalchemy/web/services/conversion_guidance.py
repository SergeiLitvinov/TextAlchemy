"""Пояснения возможностей и ограничений доступных направлений конвертации."""

from __future__ import annotations

from textalchemy.core.types import DocFormat


def route_guidance(source: DocFormat, target: DocFormat) -> list[str]:
    notes = []
    if source is DocFormat.EPUB:
        notes.append(
            "EPUB: сохраняются главы, ссылки, изображения и базовое оформление. "
            "Сложный CSS и точная разбивка на страницы не воспроизводятся."
        )
    if target is DocFormat.PPTX:
        notes.append(
            "PowerPoint: текст, фигуры, таблицы и поддерживаемые диаграммы создаются как редактируемые объекты. "
            "SVG сохраняется изображением, а не набором фигур."
        )
        notes.append(
            "У диаграмм поддерживаются подписи, цвета точек, промежутки столбцов и настройки секторов. "
            "Сложное оформление упрощается; проверьте результат в PowerPoint или LibreOffice."
        )
        notes.append(
            "Исходные темы, макеты и анимации презентаций не восстанавливаются. "
            "Режим максимального визуального сходства для этого экспорта не предлагается."
        )
    if target is DocFormat.TXT:
        notes.append(
            "TXT: текст сохраняется в UTF-8, включая пустые строки. "
            "Оформление, интерактивные ссылки и графические объекты не сохраняются; "
            "для изображений используется альтернативный текст."
        )
    if source is DocFormat.PPTX and target is DocFormat.MODEL:
        notes.append(
            "Модель документа позволяет изменить содержимое и затем загрузить её для экспорта в PowerPoint. "
            "Редактора объектов презентации в веб-интерфейсе пока нет."
        )
    return notes
